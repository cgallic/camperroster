/**
 * Rebuilds Camp Hope's five Elexio registration forms in Camper Roster's form
 * model (GitHub issue #16). Reads the Ministry Forms JSON for each form and
 * writes three files, so the mapping is reproducible rather than retyped:
 *
 *   src/lib/camp-hope-forms.ts          the converted forms, for tests and review
 *   supabase/seed/camp-hope-forms.sql   unpublished v1 drafts for each 2027 period
 *   supabase/seed/camp-hope-pricing.sql per-camper tuition tiers from the forms
 *
 * The JSON lives in the CMO repo. Export it, then run:
 *
 *   mkdir -p /tmp/elexio && for f in new-families returning-families \
 *     new-adult-volunteers returning-adult-volunteers teen-volunteers; do
 *     git -C ../cmo_agent show origin/main:clients/camp-hope/knowledge/elexio-forms/$f.json > /tmp/elexio/$f.json
 *   done
 *   node --experimental-strip-types scripts/convert-elexio-forms.ts /tmp/elexio
 */
